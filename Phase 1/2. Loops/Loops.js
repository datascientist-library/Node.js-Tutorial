console.log("Types of loops")

// 1. for loop
console.log("1. for loop")

for (let i = 0; i < 5; i++) {
  console.log("Count:", i);
}


// 2. while loop
console.log("2. while loop")

let j = 1;

while (j < 6) {
  console.log("Count:", j);
  j++;
}

// 3. do while loop
console.log("3. do while loop")

let k = 1;

do {
  console.log("Count:", k);
  k++;
} while (k < 6);